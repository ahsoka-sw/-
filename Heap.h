#pragma once
#include <vector>

using namespace std;

// Класс куча на основе вектора
class Heap {
private:
    vector<int> data;

    // Просеивание элемента вверх для восстановления свойств кучи
    void siftUp(int idx);

    // Просеивание элемента вниз для восстановления свойств кучи
    void siftDown(int idx);

public:
    // Конструктор кучи
    Heap();

    // Добавление нового элемента в кучу
    void push(int val);

    // Удаление максимального (верхнего) элемента из кучи
    void pop();

    // Получение значения максимального элемента кучи
    int top();

    // Получение количества элементов в куче
    int size();

    // Проверка кучи на пустоту
    bool empty();
};
