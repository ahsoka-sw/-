#pragma once

// Узел односвязного списка для стека
struct Node {
    int val;
    Node* next;

    // Конструктор узла
    Node(int v);
};

// Класс стек
class Stack {
private:
    Node* head;
    int sz;

public:
    // Конструктор стека
    Stack();

    // Деструктор стека (очистка памяти)
    ~Stack();

    // Добавление элемента на вершину стека
    void push(int val);

    // Удаление элемента с вершины стека
    void pop();

    // Получение значения верхнего элемента стека
    int top();

    // Получение текущего количества элементов в стеке
    int size();

    // Проверка стека на пустоту
    bool empty();
};
